class FailingAfter(OfflineEmbeddingProvider):
    """Embeds ``batches`` batches, then fails as an unavailable provider would."""

    def __init__(self, batches):
        super().__init__()
        self.remaining = batches

    def embed(self, texts, *, profile, task):
        if self.remaining == 0:
            raise EmbeddingProviderUnavailable("provider unavailable (503 UNAVAILABLE)")
        self.remaining -= 1
        return super().embed(texts, profile=profile, task=task)


def test_a_provider_failure_resumes_without_duplicate_vectors(conn, analysis):
    chunks = index_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE).chunks
    assert chunks > 4
    with pytest.raises(EmbeddingProviderUnavailable):
        embed_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE, OFFLINE_EMBEDDING_PROFILE, FailingAfter(2),
                              batch_size=2, commit_each_batch=True)
    assert embeddings_of(conn, analysis) == 4  # two committed batches survive the failure

    healthy = OfflineEmbeddingProvider()
    resumed = embed_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE, OFFLINE_EMBEDDING_PROFILE, healthy,
                                    batch_size=2, commit_each_batch=True)
    assert (resumed.already_current, resumed.embedded) == (4, chunks - 4)
    assert sum(len(call) for call in healthy.calls) == chunks - 4  # nothing is embedded twice
    assert embeddings_of(conn, analysis) == chunks
    assert scalar(conn, "SELECT count(*) FROM (SELECT chunk_id FROM semantic.embedding e JOIN semantic.chunk c "
                        "ON c.id = e.chunk_id WHERE c.analysis_id = %s GROUP BY chunk_id, embedding_profile_id "
                        "HAVING count(*) > 1) d", analysis) == 0


def test_an_incompatible_provider_is_refused_before_anything_is_written(conn, analysis):
    index_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE)
    provider = OfflineEmbeddingProvider()
    with pytest.raises(EmbeddingProfileIncompatible):
        embed_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE, DEFAULT_EMBEDDING_PROFILE, provider)
    assert provider.calls == [] and embeddings_of(conn, analysis) == 0
    assert scalar(conn, "SELECT count(*) FROM semantic.embedding_profile WHERE configuration_fingerprint = %s",
                  DEFAULT_EMBEDDING_PROFILE.fingerprint) == 0


def test_documents_are_embedded_with_their_identifiers(conn, analysis):
    index_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE)
    provider = OfflineEmbeddingProvider()
    embed_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE, OFFLINE_EMBEDDING_PROFILE, provider)
    texts = [text for call in provider.calls for text in call]
    add = next(t for t in texts if t.endswith("    def add(self, item):\n        return item"))
