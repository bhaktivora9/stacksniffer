@pytest.mark.skipif(shutil.which("git") is None, reason="git is not installed")
def test_a_parked_analysis_is_indexed_without_acquisition_or_extraction(conn, tmp_path):
    from test_analysis_postgres import _process_claimed
    from test_extraction_postgres import counts

    from backend.services.semantic.stage import SemanticIndexingStage

    source, sha = _repository(tmp_path)
    created = _queued(conn, sha)
    acquisitions = []
    acquirer = _acquirer(tmp_path, source, acquisitions)
    first = asyncio.run(_process_claimed(conn, _pipeline(conn, acquirer), created))  # no indexing deployed
    assert _state(conn, created.analysis_id) == ("AWAITING_STAGE", "EXTRACTING", "INDEXING")
    structural = counts(conn, created.analysis_id)

    # Indexing is deployed, but the provider fails: the resumed attempt fails, nothing is re-acquired.
    flaky = SemanticIndexingStage(lambda: conn, FailingAfter(1), embedding_profile=OFFLINE_EMBEDDING_PROFILE,
                                  batch_size=2)
    analysis_id, second = _resume(conn, _pipeline(conn, acquirer, flaky), created.analysis_id)
    assert analysis_id == created.analysis_id and second != first
    assert _state(conn, analysis_id) == ("FAILED", "EXTRACTING", "INDEXING")
    assert scalar(conn, "SELECT failure_code FROM core.analysis_attempt WHERE id = %s", second) \
        == "EMBEDDING_PROVIDER_UNAVAILABLE"
    chunks, partial = _semantic_counts(conn, analysis_id)
    assert partial == 2 and chunks > partial

    # A retry resumes at INDEXING, embeds only what is missing, and parks awaiting PROJECTING.
    from backend.services.analysis_lifecycle import requeue_failed_analysis

    asyncio.run(requeue_failed_analysis(conn, analysis_id, requested_by="pytest"))
    assert _state(conn, analysis_id) == ("AWAITING_STAGE", "EXTRACTING", "INDEXING")
    healthy = OfflineEmbeddingProvider()
    healthy_stage = SemanticIndexingStage(lambda: conn, healthy, embedding_profile=OFFLINE_EMBEDDING_PROFILE)
    _, third = _resume(conn, _pipeline(conn, acquirer, healthy_stage), created.analysis_id)

    assert _state(conn, analysis_id) == ("AWAITING_STAGE", "INDEXING", "PROJECTING")
    assert acquisitions == [first]  # acquired once, by the extracting attempt
    assert counts(conn, analysis_id) == structural  # extracted once
    assert _semantic_counts(conn, analysis_id) == (chunks, chunks)
    assert sum(len(call) for call in healthy.calls) == chunks - partial
    assert list((tmp_path / "work").iterdir()) == []


