def test_chunks_come_from_retained_source_and_map_to_entities_and_exact_evidence(conn, analysis):
    result = index_analysis_chunks(conn, analysis, DEFAULT_CHUNK_PROFILE)
    assert result.created == result.chunks > 0
    rows = conn.fetch_all(
        "SELECT c.chunk_kind, f.path, e.stable_key, e.entity_type, c.start_line, c.end_line, c.start_byte, "
        "c.end_byte, c.content, c.metadata->>'section', e.start_line, e.end_line "
        "FROM semantic.chunk c JOIN core.source_file f ON f.id = c.file_id JOIN core.entity e ON e.id = c.entity_id "
        "WHERE c.analysis_id = %s ORDER BY f.path, c.ordinal", str(analysis))
    assert len(rows) == result.chunks  # every chunk names a canonical entity
    kinds = {(path, kind) for kind, path, *_ in rows}
    assert kinds == {("app/cart.py", "CODE"), ("app/cart.py", "CLASS"), ("app/cart.py", "METHOD"),
                     ("app/cart.py", "FUNCTION"), ("config/app.yaml", "CONFIGURATION"),
                     ("README.md", "DOCUMENTATION")}
    retained = {path: FILES[path] for path in FILES}
    for kind, path, key, entity_type, start, end, start_byte, end_byte, content, section, e_start, e_end in rows:
        assert retained[path][start_byte:end_byte].decode() == content  # exact bytes of the analyzed file
        assert e_start <= start <= end <= e_end  # inside its entity's evidence
        if kind in ("CODE", "CONFIGURATION", "DOCUMENTATION"):
            assert (entity_type, key) == ("FILE", f"file:{path}")
        else:
            assert entity_type == kind
    assert [row[9] for row in rows if row[1] == "README.md"] == ["# Cart", "## Usage"]


