def _repository(tmp_path):
    from test_analysis_postgres import _local_repository

    source, _ = _local_repository(tmp_path)
    for path in ("svc.py", "config/app.yaml", "README.md", "app/settings.py"):
        content = {"svc.py": FILES["app/cart.py"], "config/app.yaml": FILES["config/app.yaml"],
                   "README.md": FILES["README.md"], "app/settings.py": FILES["app/settings.py"]}[path]
        (source / path).parent.mkdir(parents=True, exist_ok=True)
        (source / path).write_bytes(content)
    identity = ["-c", "user.name=t", "-c", "user.email=t@example.com"]
    subprocess.run(["git", *identity, "add", "-A"], cwd=source, check=True, capture_output=True)
    subprocess.run(["git", *identity, "commit", "-qm", "two"], cwd=source, check=True, capture_output=True)
    sha = subprocess.run(["git", "rev-parse", "HEAD"], cwd=source, check=True, capture_output=True,
                         text=True).stdout.strip()
    return source, sha


def _queued(conn, sha):
    from backend.services.analysis_persistence import create_or_reuse_analysis

    name = f"repo-{uuid4().hex[:8]}"
    return create_or_reuse_analysis(
        conn, canonical_repository_key=f"github:test-owner/{name}", owner_name="test-owner", repository_name=name,
        clone_url=f"https://github.com/test-owner/{name}.git", requested_reference="main",
        resolved_commit_sha=sha, structural_pipeline_version="structural-test")


def _pipeline(conn, acquirer, indexing=None):
    from backend.services.analysis_pipeline import AnalysisPipeline
    from backend.services.extraction.stage import StructuralExtractionStage

    return AnalysisPipeline(lambda: conn, acquirer, ownership_check_seconds=60,
                            structural_stage=StructuralExtractionStage(lambda: conn, next_stage=indexing))


def _acquirer(tmp_path, source, acquisitions):
    from backend.services.repository_acquisition import GitRepositoryAcquirer

    class CountingAcquirer(GitRepositoryAcquirer):
        def acquire(self, request, **kwargs):
            acquisitions.append(request.attempt_id)
            return super().acquire(request, **kwargs)

    return CountingAcquirer(workdir_root=tmp_path / "work", remote_url_for=lambda key: source.as_uri(),
                            allowed_protocols=("file",))


def _resume(conn, pipeline, expected):
    from backend.services.analysis_worker import _failure_of, claim_analysis_transactionally, complete_attempt

    claimed = claim_analysis_transactionally(lambda: conn, pipeline.resumable_stages)
    if claimed is None or claimed[0] != expected:
        pytest.skip("another parked analysis is ahead of the test row")
    analysis_id, attempt_id = claimed
    try:
        outcome = asyncio.run(pipeline(analysis_id, attempt_id))
        asyncio.run(complete_attempt(lambda: conn, analysis_id=analysis_id, attempt_id=attempt_id, outcome=outcome))
    except Exception as exc:
        code, detail = _failure_of(exc)
        asyncio.run(complete_attempt(lambda: conn, analysis_id=analysis_id, attempt_id=attempt_id, outcome="FAILED",
                                     failure_code=code, failure_detail=detail))
    return analysis_id, attempt_id


def _state(conn, analysis_id):
    from backend.routers.analyses import _get_analysis

    state = _get_analysis(conn, analysis_id)
    return state.status, state.last_completed_stage, state.awaiting_stage


def _semantic_counts(conn, analysis_id):
    return (scalar(conn, "SELECT count(*) FROM semantic.chunk WHERE analysis_id = %s", analysis_id),
            embeddings_of(conn, analysis_id))


@pytest.mark.skipif(shutil.which("git") is None, reason="git is not installed")
def test_a_fresh_analysis_is_indexed_and_parks_awaiting_projecting(conn, tmp_path):
    from test_analysis_postgres import _process_claimed

    from backend.services.semantic.stage import SemanticIndexingStage

    source, sha = _repository(tmp_path)
    created = _queued(conn, sha)
    acquisitions = []
    stage = SemanticIndexingStage(lambda: conn, OfflineEmbeddingProvider(), embedding_profile=OFFLINE_EMBEDDING_PROFILE)
