def run_stage(conn, analysis_id, provider, **options):
    from types import SimpleNamespace

    from backend.services.semantic.stage import SemanticIndexingStage

    stage = SemanticIndexingStage(lambda: conn, provider, embedding_profile=OFFLINE_EMBEDDING_PROFILE, **options)
    attempt_id = uuid4()  # the stage reads only the identifiers of the extraction result
    return asyncio.run(stage(SimpleNamespace(analysis_id=analysis_id, attempt_id=attempt_id))), attempt_id


def test_reprocessing_identical_content_reuses_chunks_and_vectors(conn, analysis):
    first_provider, second_provider = OfflineEmbeddingProvider(), OfflineEmbeddingProvider()
    assert run_stage(conn, analysis, first_provider)[0] == "AWAITING_STAGE"
    outcome, attempt_id = run_stage(conn, analysis, second_provider)
    assert outcome == "AWAITING_STAGE" and second_provider.calls == []
    metrics = conn.fetch_scalar("SELECT metadata->'indexing'->%s FROM core.analysis WHERE id = %s",
                                str(attempt_id), str(analysis))
    assert metrics["chunks_created"] == 0 and metrics["chunks_reused"] == metrics["chunks"] > 0
    assert metrics["vectors_created"] == 0 and metrics["vectors_reused"] == metrics["chunks"]
    assert metrics["exclusions"]["SECRET"] == 2


