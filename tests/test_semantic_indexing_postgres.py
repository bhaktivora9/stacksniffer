class SharedConnection:
    """One transaction for everything: commit, rollback and close are no-ops."""

    def __init__(self, conn):
        self._conn = conn

    def __getattr__(self, name):
        return getattr(self._conn, name)

    def commit(self):
        pass

    def rollback(self):
        pass

    def close(self):
        pass


